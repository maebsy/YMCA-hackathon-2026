-- 72hours 서비스 DB 스키마 (Supabase / PostgreSQL)
-- 적용 전제와 migration 순서: docs/db-erd.md#스키마-적용-순서
-- auth.users가 있는 대상 DB에 적용하며 SQLite에는 실행하지 않음
-- 저장·인증 모드와 ERD: docs/db-erd.md
-- 공개 데모의 검사·리포트는 로그인 불필요. Supabase 인증은 별도 설정 모드
-- 가입 계정은 Supabase Auth가 관리하는 auth.users 를 씀 (Supabase 프로젝트에 기본으로 있음)

begin;

-- 무료 데모 플랜 하나. 한도 컬럼의 null은 미설정이며 결제 기능은 없음.
-- 현재 접수 API는 이 한도 값을 읽어 제한하지 않음. SQL 변경만으로 사용량 제한이 적용되지 않음.
create table if not exists public.plan (
  code text primary key check (code = 'demo'),
  name text not null default '무료 데모',
  monthly_price integer not null default 0 check (monthly_price = 0),
  max_projects integer check (max_projects > 0),
  max_scans_per_day integer check (max_scans_per_day > 0)
);
insert into public.plan(code) values ('demo') on conflict (code) do nothing;

-- ─────────────────────────────────────────────
-- 1. profile : 가입한 사용자의 서비스 정보 (auth.users 와 1:1)
--    이메일은 auth.users 에만 있고 여기에는 복사하지 않음
-- ─────────────────────────────────────────────
create table if not exists public.profile (
  id            uuid primary key references auth.users (id) on delete cascade,
  display_name  text,
  avatar_url    text,
  created_at    timestamptz not null default now()
);
comment on table public.profile is '가입한 사용자. 가입하면 트리거가 자동으로 만듦';
alter table public.profile add column if not exists plan_code text not null default 'demo'
  references public.plan(code);

-- auth.users 행 생성 때 profile 자동 생성. 사용자 메타데이터에서 이름·사진을 가져옴
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profile (id, display_name, avatar_url)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'user_name',   -- GitHub 아이디
             new.raw_user_meta_data ->> 'full_name',   -- Google·GitHub 이름
             new.raw_user_meta_data ->> 'name',
             split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'avatar_url',
             new.raw_user_meta_data ->> 'picture')
  );
  return new;
end;
$$;
revoke all on function public.handle_new_user() from public;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 스키마 적용 전에 이미 가입한 사용자도 profile을 갖게 함. 기존 프로필은 덮어쓰지 않음.
insert into public.profile(id, display_name, avatar_url)
select id, coalesce(raw_user_meta_data ->> 'user_name', raw_user_meta_data ->> 'full_name',
                    raw_user_meta_data ->> 'name', split_part(email, '@', 1)),
       coalesce(raw_user_meta_data ->> 'avatar_url', raw_user_meta_data ->> 'picture')
from auth.users on conflict (id) do nothing;

-- ─────────────────────────────────────────────
-- 2. project : 검사 대상 공개 GitHub 저장소
--    익명 검사에는 owner_id 없이 job UUID의 SHA-256 해시를 저장
--    현재 검사 저장은 검사마다 새 프로젝트를 생성하며 계정으로 이전하는 claim API는 없음
-- ─────────────────────────────────────────────
create table if not exists public.project (
  id                bigint generated by default as identity primary key,
  owner_id          uuid references public.profile (id) on delete cascade,  -- null = 로그인 없이 만든 프로젝트
  claim_token_hash  text,             -- 익명 검사 job UUID의 SHA-256 해시 (이 컬럼에는 원문을 저장하지 않음)
  name              text not null check (char_length(name) between 1 and 100),
  site_url          text check (site_url ~ '^https?://'),
  repo_url          text not null check (repo_url ~ '^https://github\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+/?$'),
  branch            text,
  created_at        timestamptz not null default now(),
  check (owner_id is not null or claim_token_hash is not null)  -- 주인도 토큰도 없는 프로젝트 금지
);
comment on table public.project is '검사 대상 사이트 (공개 GitHub 저장소). 주인(가입 사용자) 또는 접근 토큰이 있어야 조회 가능';

create index if not exists project_owner_idx on public.project (owner_id) where owner_id is not null;
create unique index if not exists project_claim_token_idx on public.project (claim_token_hash) where claim_token_hash is not null;

-- ─────────────────────────────────────────────
-- 3. scan : 검사 1회 (검사 엔진을 한 번 돌린 기록)
-- ─────────────────────────────────────────────
create table if not exists public.scan (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references public.project (id) on delete cascade,
  status       text not null default 'queued'
               check (status in ('queued', 'fetching', 'scanning', 'normalizing', 'explaining', 'done', 'failed')),
  branch       text,
  commit_sha   text,                  -- 소스를 받은 뒤 채움, 재검사 비교 기준
  error        jsonb,                 -- {"code": "CLONE_TIMEOUT", "message": "..."}
  summary      jsonb,                 -- {"total": 12, "critical": 1, "high": 3, ...}
  created_at   timestamptz not null default now(),
  started_at   timestamptz,
  finished_at  timestamptz
);
comment on table public.scan is '검사 1회. status: queued → fetching → scanning → normalizing → explaining → done | failed';

create index if not exists scan_project_created_idx on public.scan (project_id, created_at desc);
-- 같은 project_id의 진행 중 검사는 1개만. 검사마다 새 프로젝트를 만드는 현재 API의 저장소 중복 접수 제한은 아님
create unique index if not exists scan_one_active_per_project on public.scan (project_id)
  where status not in ('done', 'failed');

-- ─────────────────────────────────────────────
-- 4. tool_run : 검사 1회 안의 스캐너별 실행 기록
-- ─────────────────────────────────────────────
create table if not exists public.tool_run (
  id             bigint generated by default as identity primary key,
  scan_id        bigint not null references public.scan (id) on delete cascade,
  tool           text not null check (tool in ('osv-scanner', 'semgrep', 'opengrep', 'gitleaks')),
  status         text not null default 'queued' check (status in ('queued', 'running', 'done', 'failed')),
  version        text,
  exit_code      int,
  duration_ms    int,
  finding_count  int,
  error          text,
  unique (scan_id, tool)
);
comment on table public.tool_run is '스캐너별 실행 결과. 하나가 실패해도 나머지로 진행';

-- 엔진의 도구명과 검사 범위 기록. 레지스트리 미사용/도구 실패를 해결로 오판하지 않도록 보관.
alter table public.tool_run drop constraint if exists tool_run_tool_check;
alter table public.tool_run add constraint tool_run_tool_check
  check (tool in ('osv', 'osv-scanner', 'semgrep', 'opengrep', 'gitleaks', 'config'));
alter table public.tool_run drop constraint if exists tool_run_status_check;
alter table public.tool_run add constraint tool_run_status_check
  check (status in ('queued', 'running', 'done', 'failed', 'skipped'));
alter table public.tool_run add column if not exists coverage jsonb not null default '{}'::jsonb;

-- ─────────────────────────────────────────────
-- 5. finding : 정규화된 발견 항목 (공통 JSON 규격)
-- ─────────────────────────────────────────────
create table if not exists public.finding (
  id                 bigint generated by default as identity primary key,
  scan_id            bigint not null references public.scan (id) on delete cascade,
  fingerprint        text not null,   -- 재검사 비교 키 (줄 번호 제외)
  tool               text not null check (tool in ('osv-scanner', 'semgrep', 'opengrep', 'gitleaks')),
  category           text not null check (category in ('dependency', 'code', 'secret')),
  rule_id            text not null,
  title              text not null,
  severity           text not null check (severity in ('critical', 'high', 'medium', 'low', 'info')),
  -- 위치 (API에서는 location 객체로 묶어서 응답)
  file_path          text,
  start_line         int check (start_line > 0),
  end_line           int check (end_line >= start_line),
  -- 라이브러리 취약점일 때만 (API에서는 package 객체)
  package_name       text,
  package_ecosystem  text,
  installed_version  text,
  fixed_version      text,
  refs               jsonb not null default '{}'::jsonb,  -- {"cve": [], "cwe": [], "urls": []} (references는 SQL 예약어라 refs)
  snippet            text,             -- 마스킹된 코드 조각
  raw                jsonb not null,   -- 마스킹된 정규화 finding 전체
  explain_status     text not null default 'none' check (explain_status in ('none', 'pending', 'done', 'failed')),
  created_at         timestamptz not null default now(),
  unique (scan_id, fingerprint),       -- 한 검사 안에서 중복 제거
  check (category <> 'dependency' or package_name is not null)
);
comment on table public.finding is '스캐너 결과를 공통 형식으로 맞춘 발견 항목. 비밀값은 저장 전에 마스킹';

-- 기존 초안이 적용된 DB도 비파괴적으로 확장. 원본 finding/설명 데이터는 유지.
alter table public.finding drop constraint if exists finding_tool_check;
alter table public.finding add constraint finding_tool_check
  check (tool in ('osv', 'osv-scanner', 'semgrep', 'opengrep', 'gitleaks', 'config'));
alter table public.finding drop constraint if exists finding_category_check;
alter table public.finding add constraint finding_category_check
  check (category in ('dependency', 'code', 'secret', 'config'));
alter table public.finding drop constraint if exists finding_severity_check;
alter table public.finding add constraint finding_severity_check
  check (severity in ('critical', 'high', 'medium', 'low', 'info', 'unknown'));
alter table public.finding drop constraint if exists finding_explain_status_check;
alter table public.finding add constraint finding_explain_status_check
  check (explain_status in ('none', 'pending', 'done', 'failed', 'skipped'));
alter table public.finding add column if not exists llm_context jsonb not null default '{}'::jsonb;
comment on column public.finding.llm_context is '서버가 저장한 LLM 보충 입력: status/change/flags/fix_hint/what/context/covers';

create index if not exists finding_fingerprint_idx on public.finding (fingerprint);  -- finding fingerprint 조회 인덱스
create index if not exists finding_scan_severity_idx on public.finding (scan_id, severity);

-- ─────────────────────────────────────────────
-- 6. explanation : LLM 설명·수정 지시
-- ─────────────────────────────────────────────
create table if not exists public.explanation (
  id                      bigint generated by default as identity primary key,
  finding_id              bigint not null references public.finding (id) on delete cascade,
  variant                 text not null default 'C' check (variant in ('B', 'C')),  -- A안(스캐너 원문)은 finding.raw
  summary                 text not null,
  why_risky               text not null,
  priority                text not null check (priority in ('now', 'soon', 'later')),
  fix_steps               jsonb not null default '[]'::jsonb,
  ai_fix_prompt           text not null,   -- AI 코딩 도구에 붙여 넣을 수정 지시
  false_positive_suspect  boolean not null default false,
  false_positive_reason   text,
  model                   text not null,
  prompt_version          text not null default 'v1',  -- 프롬프트를 바꿔 가며 비교할 때
  latency_ms              int,
  created_at              timestamptz not null default now(),
  unique (finding_id, variant)
);
alter table public.explanation drop constraint if exists explanation_variant_check;
alter table public.explanation add constraint explanation_variant_check check (variant in ('B', 'C', 'D'));
alter table public.explanation add column if not exists attack_scenario text;
alter table public.explanation add column if not exists red_verdict text;
alter table public.explanation add column if not exists red_rounds jsonb not null default '[]'::jsonb;
alter table public.explanation add column if not exists needs_manual_review boolean not null default true;
alter table public.explanation add column if not exists completion_tokens integer;
alter table public.explanation add column if not exists covers jsonb not null default '[]'::jsonb;
comment on table public.explanation is 'LLM 설명: C=Blue, D=Red-Blue. B는 과거 기록 보존용. 실제 코드 수정 완료 의미 아님';

-- ─────────────────────────────────────────────
-- 보안: RLS 켜기 (정책 없음)
-- 권한이 높은 DB 계정은 RLS를 우회할 수 있으므로 인증 모드 API의 소유권 검사도 필요.
-- 서비스 데이터는 FastAPI로 접근하며, 현재 공개 프론트에는 Supabase 로그인이 연결되어 있지 않음.
-- 아래 RLS와 권한 회수는 anon·authenticated 역할의 이 서비스 테이블 직접 접근을 제한.
-- ─────────────────────────────────────────────
alter table public.profile     enable row level security;
alter table public.project     enable row level security;
alter table public.scan        enable row level security;
alter table public.tool_run    enable row level security;
alter table public.finding     enable row level security;
alter table public.explanation enable row level security;
alter table public.plan        enable row level security;

-- 익명/로그인 클라이언트가 직접 데이터 테이블에 접근하는 정책은 만들지 않음.
revoke all on public.plan, public.profile, public.project, public.scan,
  public.tool_run, public.finding, public.explanation from public;

-- Supabase는 anon·authenticated 역할에 public 스키마 테이블 권한을 따로 줍니다(기본 권한).
-- 위의 "from public"으로는 회수되지 않고, TRUNCATE는 RLS를 거치지 않아 두 역할이 데이터를 통째로 지울 수 있습니다.
-- 두 역할이 있을 때만 명시적으로 회수합니다. 역할이 없으면 아래 블록은 해당 회수를 생략합니다.
do $$
declare client text;
begin
  foreach client in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = client) then
      execute format('revoke all on public.plan, public.profile, public.project, public.scan, '
                     'public.tool_run, public.finding, public.explanation from %I', client);
      execute format('revoke all on all sequences in schema public from %I', client);
    end if;
  end loop;
end $$;

commit;
