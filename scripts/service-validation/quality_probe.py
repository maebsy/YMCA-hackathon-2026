"""일반 서버에서 독립 정답 검증을 실행하고 공개 가능한 결과만 현재 실행에 보관합니다."""
import json
from pathlib import Path
import re
import shutil
import subprocess
import uuid


def collect(alias, public):
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]{0,100}', alias):
        raise ValueError('SSH config 별칭이 필요합니다.')
    name = uuid.uuid4().hex
    remote = 'apps/72hours/validation/quality-runs/'+name+'.json'
    command = ('apps/72hours/current/.venv/bin/python apps/72hours/validation/code/engine_quality.py '
               '--source apps/72hours/current --output '+remote)
    process = subprocess.run(['ssh','-o','BatchMode=yes','-o','ConnectTimeout=8',alias,command],
                             capture_output=True, timeout=300)
    if process.returncode not in (0, 1):
        raise RuntimeError('엔진 정답 검증 실행/SSH 실패')
    destination = public/'engine-quality.json'
    subprocess.run(['scp','-q','-o','BatchMode=yes',alias+':'+remote,str(destination)],
                   capture_output=True, check=True, timeout=30)
    data = json.loads(destination.read_text(encoding='utf-8'))
    if not data.get('finished_at') or data.get('status') not in ('passed','failed'):
        raise RuntimeError('엔진 정답 검증이 완료되지 않았습니다.')
    shutil.copyfile(Path(__file__).with_name('quality.html'), public/'quality.html')
    # File is generated by this invocation, then published as latest only after completion.
    subprocess.run(['ssh','-o','BatchMode=yes',alias,
                    'cp '+remote+' apps/72hours/validation/engine-quality-latest.json.next && mv -f apps/72hours/validation/engine-quality-latest.json.next apps/72hours/validation/engine-quality-latest.json'],
                   capture_output=True, check=True, timeout=20)
    return {'status': data['status'], 'source_revision': data['source_revision'],
            'passed':sum(c['status']=='pass' for c in data['checks']),
            'failed':sum(c['status']=='fail' for c in data['checks']), 'labeled_metrics':data['labeled_metrics']}
